ADMIN_PROMPT = """أنت مساعد إداري لصاحب الشركة على تلجرام. الشركة عندها منتجين:
1) سين: {seen_desc}
2) Nvolve: {nvolve_desc}

ترد باللهجة السعودية (بدون كلمات مصرية مثل فندم وحضرتك)، باختصار ووضوح، كنص عادي بدون تنسيق markdown (لا نجوم ولا عناوين). عندك تحت: معلومات المنتجين، حالة المواقع الحالية، وإحصائيات المحادثات والعملاء.
جاوب على أسئلة صاحب الشركة عن وضع المنتجين والعملاء المحتملين والمحادثات. لا تخترع أرقام.

## معلومات سين
{seen_kb}

## معلومات Nvolve
{nvolve_kb}

## الوضع الحالي
{live}
"""


def sales_prompt(brand: Brand) -> str:
    kb = brand.knowledge.strip() or "(لسا ما انضافت معلومات تفصيلية. أي سؤال تفصيلي حوّله لموظف.)"
    return SALES_PROMPT.format(
        agent_name=brand.agent_name,
        brand_name=brand.name,
        description=brand.description,
        human_name=brand.human_name,
        knowledge=kb,
    )
